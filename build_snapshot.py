#!/usr/bin/env python3
"""Generate a browser-readable snapshot for directly opening index.html."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def build_snapshot():
    components = ROOT / "docs" / "Components"
    entries = []
    for path in sorted(components.iterdir(), key=lambda p: p.name.casefold()):
        if path.is_file() and not path.is_symlink() and path.suffix.lower() in (".html", ".htm"):
            entries.append({"fileName": path.name,
                            "html": path.read_text(encoding="utf-8-sig", errors="replace"),
                            "lastModified": path.stat().st_mtime * 1000})
    output = ROOT / "docs" / "components-snapshot.js"
    content = "// Generated by build_snapshot.py. Do not edit manually.\nwindow.COMPONENT_SNAPSHOT = " + json.dumps(entries, ensure_ascii=False) + ";\n"
    if not output.exists() or output.read_text(encoding="utf-8") != content:
        temp = output.with_suffix(".js.tmp")
        temp.write_text(content, encoding="utf-8")
        temp.replace(output)
    return len(entries)


if __name__ == "__main__":
    print("已更新本地首页索引：" + str(build_snapshot()) + " 份财报")
